const { _electron } = require('playwright-core');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
(async () => {
  const root = path.resolve('test-output/appearance');
  await fs.mkdir(root, { recursive: true });
  const profile = path.join(root, 'profile');
  await fs.rm(profile, { recursive: true, force: true });
  const env = { ...process.env, SHIYIN_TEST:'1', SHIYIN_TEST_DATA:profile }; delete env.ELECTRON_RUN_AS_NODE;
  const launch = () => _electron.launch({ args:[path.resolve('.')], env, timeout:30000 });
  let app = await launch();
  try {
    let page = await app.firstWindow(); page.setDefaultTimeout(15000);
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.waitForFunction(() => document.querySelector('#output-path').textContent.length > 0);
    assert.equal((await page.evaluate(() => window.shiyin.state())).theme, 'system');
    assert.equal(await app.evaluate(({ nativeTheme }) => nativeTheme.themeSource), 'system');
    const firstGreeting = await page.locator('#intro-title').textContent();
    await page.reload();
    await page.waitForFunction(previous => document.querySelector('#intro-title').textContent !== previous, firstGreeting);
    await page.waitForFunction(() => document.querySelector('.queue').getAnimations().every(animation => animation.playState === 'finished'));
    const greeting = await page.locator('#intro-title').textContent();
    await page.emulateMedia({ colorScheme:'dark' });
    await page.waitForFunction(() => getComputedStyle(document.body).backgroundColor === 'rgb(23, 23, 28)');
    await page.emulateMedia({ colorScheme:'light' });
    await page.waitForFunction(() => getComputedStyle(document.body).backgroundColor === 'rgb(250, 250, 251)');
    await page.emulateMedia({ colorScheme:null });
    await page.click('[data-theme="light"]');
    await page.waitForFunction(() => document.querySelector('[data-theme="light"]').getAttribute('aria-pressed') === 'true');
    await page.waitForFunction(() => getComputedStyle(document.body).backgroundColor === 'rgb(250, 250, 251)');
    await page.waitForFunction(() => getComputedStyle(document.querySelector('h1')).color === 'rgb(41, 41, 47)');
    await page.screenshot({ path:path.join(root, 'light.png') });
    await page.click('[data-theme="dark"]');
    await page.waitForFunction(() => document.querySelector('[data-theme="dark"]').getAttribute('aria-pressed') === 'true');
    await page.waitForFunction(() => getComputedStyle(document.body).backgroundColor === 'rgb(23, 23, 28)');
    await page.waitForFunction(() => getComputedStyle(document.querySelector('h1')).color === 'rgb(238, 234, 240)');
    assert.equal(await app.evaluate(({ nativeTheme }) => nativeTheme.shouldUseDarkColors), true);
    await page.screenshot({ path:path.join(root, 'dark.png') });
    assert.equal(await page.locator('#intro-title').textContent(), greeting, 'theme updates must not reshuffle the greeting');
    const before = await page.locator('.record').evaluate(element => getComputedStyle(element).transform);
    await page.waitForFunction(transform => getComputedStyle(document.querySelector('.record')).transform !== transform, before);
    const bounds = await page.locator('#dropzone').boundingBox();
    await page.mouse.move(bounds.x + bounds.width * .8, bounds.y + 30);
    await page.waitForFunction(() => Math.abs(parseFloat(document.querySelector('.art-parallax').style.getPropertyValue('--tilt-y'))) > 1);
    await page.mouse.move(10, 10);
    await page.waitForFunction(() => Math.abs(parseFloat(document.querySelector('.art-parallax').style.getPropertyValue('--tilt-y'))) < .03);
    await page.emulateMedia({ reducedMotion:'reduce' });
    const still = await page.locator('.record').evaluate(element => getComputedStyle(element).transform);
    await page.mouse.move(bounds.x + bounds.width * .8, bounds.y + 30);
    assert.equal(await page.locator('.record').evaluate(element => getComputedStyle(element).animationName), 'none');
    assert.equal(await page.locator('.record').evaluate(element => getComputedStyle(element).transform), still);
    await page.emulateMedia({ reducedMotion:'no-preference' });
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(800, 620));
    await page.screenshot({ path:path.join(root, 'dark-small.png') });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    const settings = JSON.parse(await fs.readFile(path.join(profile, 'settings.json'), 'utf8'));
    assert.equal(settings.theme, 'dark'); assert.ok(settings.outputDir);
    await app.close();
    app = await launch(); page = await app.firstWindow();
    await page.waitForFunction(() => document.querySelector('[data-theme="dark"]').getAttribute('aria-pressed') === 'true');
    assert.equal(await app.evaluate(({ nativeTheme }) => nativeTheme.themeSource), 'dark');
    assert.equal((await page.evaluate(() => window.shiyin.state())).outputDir, settings.outputDir);
    assert.deepEqual(errors, []);
    console.log('PASS: system-following appearance, manual light/dark, persisted preference, random non-repeating greetings, continuous record motion, spring interaction and settling, reduced motion, and compact dark layout.');
  } finally { await app.evaluate(({ app }) => app.exit(0)).catch(() => {}); await app.close().catch(() => {}); }
})().catch(error => { console.error(error); process.exitCode = 1; });
